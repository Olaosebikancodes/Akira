// Builds src/render/transitions/catalog.ts and THIRD_PARTY_NOTICES.md from the
// gl-transitions package. Run with `npm run generate:transitions` after upgrading it.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const engine = path.join(here, "..");
const require = createRequire(import.meta.url);
const packageDir = path.dirname(require.resolve("gl-transitions/package.json"));
const { version } = JSON.parse(readFileSync(path.join(packageDir, "package.json"), "utf8"));
const metadata = JSON.parse(readFileSync(path.join(packageDir, "gl-transitions.json"), "utf8"));

/** Only licences that allow shipping inside an MIT project with attribution. */
const ALLOWED_LICENSES = new Set(["MIT", "BSD 2 Clause", "BSD 3 Clause"]);

const included = [];
const skipped = [];
for (const transition of metadata) {
  if (transition.textures?.length) {
    skipped.push(`${transition.name} (needs extra images)`);
    continue;
  }
  if (!ALLOWED_LICENSES.has(transition.license)) {
    skipped.push(`${transition.name} (licence: ${transition.license})`);
    continue;
  }
  const source = readFileSync(path.join(packageDir, "glsl3", `${transition.name}.glsl`), "utf8");
  // Drop the comment header; attribution lives in THIRD_PARTY_NOTICES.md.
  const glsl = source
    .split("\n")
    .filter((line) => !/^\/\/ (.* — GLSL ES|Author|License|Description|Tags)/.test(line))
    .join("\n")
    .trim();
  const params = {};
  for (const [name, type] of Object.entries(transition.paramsTypes ?? {})) {
    params[name] = { type, value: transition.defaultParams[name] };
  }
  included.push({
    name: transition.name,
    label: label(transition.name),
    author: transition.author,
    license: transition.license,
    tags: transition.tags ?? [],
    glsl,
    params,
  });
}

/** "CircleOpen" becomes "Circle open". */
function label(name) {
  const words = name.replace(/([a-z0-9])([A-Z])/g, "$1 $2").split(" ");
  return [words[0], ...words.slice(1).map((word) => (word.length > 1 && word === word.toUpperCase() ? word : word.toLowerCase()))].join(" ");
}

const catalog = `// Generated by scripts/generate-transitions.mjs from gl-transitions ${version}. Do not edit.
// Authors and licences are listed in THIRD_PARTY_NOTICES.md.
import type { TransitionDefinition } from "./types";

export const TRANSITIONS: readonly TransitionDefinition[] = ${JSON.stringify(included, null, 2)};
`;
writeFileSync(path.join(engine, "src/render/transitions/catalog.ts"), catalog);

